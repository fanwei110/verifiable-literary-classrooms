"""裁判自我偏好风险的描述性分层（回应 R3.4；post hoc，不做检验）。

事实更正：60 题冻结裁判集抽自会议冻结网格 runs/raw/formal/formal_corr.jsonl，
该网格的三个生成模型是 mistralai/mistral-large-2512、deepseek/deepseek-v4-pro、
qwen/qwen3-235b-a22b-2507（其 M 编号与期刊扩展网格的 M1–M4 不同，见 out/model_grid_map.md）。
裁判 deepseek-v4-pro 与其中一个生成模型同名：部分题目由裁判同名模型生成，裁判集不含任何
期刊网格 M4（deepseek-reasoner）的输出。同名标识不证明底层权重或服务路由相同。

做法：按"生成者是否与裁判同名"分层，报告两位裁判在主口径（记录级）标签下对错误题的接受率；
GPT 裁判与任何生成模型都不同名，作为对照，看差异是否只是题目组成造成。
输出 out/judge_self_generation.md、out/model_grid_map.md。
"""
from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

import r2_common as C
import judge_label_audit as JA

OUT = Path(__file__).resolve().parent / "out"


def main() -> None:
    C.utf8_stdout()
    items = JA.rebuild_items()
    JA.verify_rebuild(items)
    audit = {r["item_id"]: r for r in csv.DictReader((OUT / "judge_item_audit.csv").open(encoding="utf-8"))}
    label = {i: audit[i]["displayed_record_label"] == "correct" for i in audit}
    slug = {i: it["run"].get("model_slug") for i, it in items.items()}
    self_gen = {i: slug[i] == "deepseek/deepseek-v4-pro" for i in items}
    scored = JA.AR.load_scored()

    comp = Counter((self_gen[i], label[i]) for i in items)
    md = ["# Judge self-generation stratification (descriptive)", "",
          f"Items generated by the judge-namesake model (deepseek/deepseek-v4-pro): {sum(self_gen.values())}/60 "
          f"({comp[(True, False)]} error, {comp[(True, True)]} correct under displayed-record labels); "
          f"other generators: {60 - sum(self_gen.values())} ({comp[(False, False)]} error, {comp[(False, True)]} correct).", "",
          "Generator counts: " + ", ".join(f"{k}: {v}" for k, v in sorted(Counter(slug.values()).items())), "",
          "| Judge | Evidence | Error items accepted: self-generated | Error items accepted: other generators | Difference (pp) |",
          "|---|---|---|---|---|"]
    diffs = defaultdict(dict)
    for model in JA.AR.MODEL_FILES:
        for cond in JA.CONDS:
            rows = [x for x in scored if x["model"] == model and x["condition"] == cond and not label[x["item_id"]]]
            a = [x for x in rows if self_gen[x["item_id"]]]
            b = [x for x in rows if not self_gen[x["item_id"]]]
            ka = sum(x["verdict"] == "accurate" for x in a)
            kb = sum(x["verdict"] == "accurate" for x in b)
            d = 100 * (ka / len(a) - kb / len(b))
            diffs[model][cond] = d
            md.append(f"| {model} | {cond} | {ka}/{len(a)} ({100*ka/len(a):.0f}%) | {kb}/{len(b)} ({100*kb/len(b):.0f}%) | {d:+.0f} |")
    gpt, ds = list(JA.AR.MODEL_FILES)
    md += ["", "Difference-in-differences (DeepSeek judge minus GPT judge, pp): " +
           ", ".join(f"{c}: {diffs[ds][c] - diffs[gpt][c]:+.0f}" for c in JA.CONDS), "",
           "Cells are small and item difficulty differs across generators, so these contrasts can neither establish "
           "nor exclude self-preference; no test is performed."]
    (OUT / "judge_self_generation.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))

    # 两套网格模型编号对照
    g = Counter()
    for r in C.read_jsonl(C.ROOT / "runs" / "raw" / "formal" / "formal_corr.jsonl"):
        g[("conference frozen grid (2,160; source of the 60 judge items)", r["model"], r.get("model_slug"))] += 1
    for tag in C.PRIMARY_TAGS:
        for r in C.read_jsonl(C.ROOT / "runs" / "raw" / f"ext_{tag}" / f"{tag}.jsonl"):
            g[("journal confirmatory grid (ext_e1c; M1–M4 in the article)", r["model"], r.get("model_slug"))] += 1
    mm = ["# Model identifiers in the two frozen grids", "", "| Grid | Log label | Model slug | Records |", "|---|---|---|---|"]
    for (grid, m, s), n in sorted(g.items()):
        mm.append(f"| {grid} | {m} | {s} | {n} |")
    (OUT / "model_grid_map.md").write_text("\n".join(mm) + "\n", encoding="utf-8")
    print("\n".join(mm))


if __name__ == "__main__":
    main()
